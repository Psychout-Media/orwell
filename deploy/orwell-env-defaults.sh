# This is the SINGLE SOURCE of the set of env vars the deploy opts into on top of the engine's
# code defaults. It is SOURCED (never executed) by BOTH:
#   • deploy/orwell-install.sh  — writes the whole set into a FRESH box's data/.env (write_config).
#   • deploy/orwell-update.sh   — BACKFILLS any of these MISSING from an existing box's data/.env
#                                 (add-if-absent, never-clobber), so a box provisioned before a flag
#                                 was added still gains it on its next update.
#
# Why this file exists: most flags below DEFAULT OFF in engine code (a few — e.g. ORWELL_NPC_MEMORY, flipped ON in code 2026-11-03 — now default ON there too, and are listed here only so install/update write them explicitly and a box's .env states its posture; the engine code default, not this list, is the source of truth for those) (so the seeded calibration + the
# gates stay byte-identical; the 0108 golden fixture that once also rode this was decommissioned 2026-07-21) and is turned ON only by the deploy. The installer used to
# hand-write them and the updater reconciled NONE of them — so an old box permanently missed whatever
# flag post-dated it (the one that got noticed: ORWELL_EMBEDDINGS unset ⇒ the engine silently runs
# DEGRADED deterministic semantic recall). Keeping the (KEY, DEFAULT) truth here means the two scripts
# cannot drift: add or change a flag in THIS file only and both the install and the backfill pick it up.
#
# The list is deploy OPT-IN FEATURE flags ONLY — it deliberately excludes the REQUIRED infra vars
# (ORWELL_ENGINE_TOKEN / _ADMIN_TOKEN / _MCP_URL / _PORT, ORWELL_PORT, ORWELL_DATA_DIR, ORWELL_BIND_HOST,
# ORWELL_ENGINE_MULTIUSER, OPENAI_API_KEY, LLM_HOSTS), which already exist on any running box and must
# never be regenerated by a reconcile (a fresh token would kill auth).
