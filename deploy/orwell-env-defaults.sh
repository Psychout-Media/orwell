# orwell_optin_env_defaults <data_dir>
#   Prints the opt-in KEY=VALUE lines — ONLY bare KEY=VALUE, one per line, in the installer's historical
#   order (no comments, so install's .env stays byte-identical and update's add-if-absent loop is clean).
#   <data_dir> is the box's data/ directory: orwell-install.sh passes ${DATA_DIR} (== ${APP_DIR}/data),
#   orwell-update.sh passes ${APP_DIR}/data — the same dir the model prefetch warms — so ORWELL_EMBED_CACHE
#   resolves to the same <data_dir>/models in both paths.
