#!/usr/bin/env python3
"""ORW-511: regenerate the scanned-site tables of docs/audits/SHORT-LISTS-INVENTORY.md from the scanner and the allowlist. The hand-written parts (the per-site decision table
for the four named sites, sections 3 to 5, the guard notes) live between the markers `<!-- hand:start -->` and `<!-- hand:end -->` and are kept as they are.
Usage: short_list_inventory.py   (rewrites the file in place)."""
import collections
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_short_lists as G  # noqa: E402
import short_list_scan as S  # noqa: E402

DOC = S.ROOT / "docs" / "audits" / "SHORT-LISTS-INVENTORY.md"
CADENCE = [
    (r"momentPrompts|agent_loop", "per turn (prompt sent every turn)"),
    (r"cast_(authoring|genesis|identity)|facet_ledger|characterFactory|deepProfile|genesisConstants|castGenesis|characters\.ts|diversity|seededRel|domain/", "per season (cast build, 16 people)"),
    (r"portrait|imageConstants", "per season (per portrait / shot)"),
    (r"producerPersona|curiosity|zeitgeist|alliances|reserveTwists", "per season (once)"),
    (r"confessionals|chat_helpers|offscreen", "per day (several a day)"),
    (r"static/js", "per session (UI text)"),
]


def cadence(p: str) -> str:
    return next((c for rx, c in CADENCE if re.search(rx, p)), "not shown to a game player (assistant/admin/tool text)")


def main() -> None:
    hits, ent = S.scan(), G.load_allowlist()
    owner = {(e["path"], e["kind"], e["name"]): e["owner"] for e in ent}
    rows: dict = collections.OrderedDict()
    for h in hits:
        k = (h.path, h.kind, h.name if h.kind == "list" else "text")
        r = rows.setdefault(k, {"lines": [], "size": h.size, "lang": h.lang})
        r["lines"].append(h.line)
    by, tot = collections.Counter(), collections.Counter()
    for (p, k, n), r in rows.items():
        c = 1 if k == "list" else 2
        by[(owner[(p, k, n)], c)] += len(r["lines"])
        tot[c] += len(r["lines"])
    cnt = lambda lang, kind: sum(1 for h in hits if h.lang == lang and h.kind == kind)  # noqa: E731
    old = DOC.read_text(encoding="utf8")
    hand = old[old.index("<!-- hand:start -->"):old.index("<!-- hand:end -->") + len("<!-- hand:end -->")]
    o = ["# Short lists across the whole product: inventory (ORW-511)\n",
         "Product owner, 2026-11-15: worry about \"the short list problem across the whole product\". Rule: nothing is dealt from a teeny list; everything is as close to unbounded as the offline floor allows, and the live writer authors from the game's own facts.\n",
         "Scanned-site tables are generated by `ci/short_list_inventory.py` from `ci/short_list_scan.py` (the scanner the CI guard `ci/check_short_lists.py` runs) over src/ TypeScript, frontend Python and frontend/static/js. Comments and docstrings are not scanned: only string literals a model or a player can receive. Numbers only; no play text. Class 1 = a string list under 40 items feeding a random, hash or modulo pick. Class 2 = \"e.g./for example/such as\" inside a string, or a closed menu. Each marker counts once. The roughly 435 raw \"e.g.\" hits on the card are almost all code comments.\n",
         "## Totals (current tree)\n", "| class | what | sites |\n|---|---|---|",
         f"| 1 | dealt string lists under 40 items (TS {cnt('ts', 'list')}, Python {cnt('py', 'list')}) | {tot[1]} |",
         f"| 2 | example lines in strings (TS {cnt('ts', 'example')}, Python {cnt('py', 'example')}, JS {cnt('js', 'example')}) and closed menus ({sum(1 for h in hits if h.kind == 'menu')}) | {tot[2]} |",
         "| 3 | model habits with no list | section 3 |\n| 4 | fixed player-facing strings | section 4 |\n| 5 | no cross-season memory | section 5 |\n",
         "| owner | class 1 lists | class 2 example/menu lines |\n|---|---|---|"]
    for ow in ["ORW-508", "ORW-509", "ORW-510", "ORW-480", "ORW-511"]:
        o.append(f"| {ow} | {by[(ow, 1)]} | {by[(ow, 2)]} |")
    o.append("\nOwner key: ORW-508 cast and character pools; ORW-509 world-side lists (PR 2843); ORW-510 live text and moment prompts; ORW-480 photo track and cast-text authoring (PRs 2821 and 2828); ORW-511 this card.\n")
    o.append(hand + "\n")
    n511 = sum(1 for e in ent if e["owner"] == "ORW-511" and e["kind"] == "list")
    o.append(f"## ORW-511: the {n511} lists\n\n| file:line | list (size) | decision |\n|---|---|---|")
    for e in ent:
        if e["owner"] == "ORW-511" and e["kind"] == "list":
            r = rows.get((e["path"], "list", e["name"]))
            o.append(f"| {e['path']}:{r['lines'][0] if r else '?'} | {e['name']} ({r['size'] if r else '?'}) | {e['decision']} |")
    o.append("\n## ORW-511: every example line and closed menu, one row per site\n\n| file:line | reason |\n|---|---|")
    for e in ent:
        if e["owner"] == "ORW-511" and e["kind"] != "list":
            for s in e["sites"]:
                o.append(f"| {e['path']}:{s['line']} | {s['reason']} |")
    o.append("\n## Lists of any length that need a recorded decision (40 or more, any owner)\n\n| file:line | list (size) | owner | decision |\n|---|---|---|---|")
    for e in ent:
        r = rows.get((e["path"], "list", e["name"]))
        if e["kind"] == "list" and r and r["size"] >= S.LIMIT:
            o.append(f"| {e['path']}:{r['lines'][0]} | {e['name']} ({r['size']}) | {e['owner']} | {e.get('decision', '')} |")
    o.append("\n## Allowlist entries waiting on another PR (transitional)\n\n| entry | until | owner |\n|---|---|---|")
    for e in ent:
        if e.get("transitional"):
            o.append(f"| {e['path']} {e['kind']} {e['name']} | {e['transitional']} | {e['owner']} |")
    o.append("\n## All other scanned sites (other owners)\n\n| file:lines | class | kind | cadence | owner |\n|---|---|---|---|---|")
    for (p, k, n), r in rows.items():
        if owner[(p, k, n)] == "ORW-511":
            continue
        ls = ",".join(map(str, r["lines"][:8])) + ("..." if len(r["lines"]) > 8 else "")
        what = f"list {n} ({r['size']})" if k == "list" else f"{k} x{len(r['lines'])}"
        o.append(f"| {p}:{ls} | {1 if k == 'list' else 2} | {what} | {cadence(p)} | {owner[(p, k, n)]} |")
    DOC.write_text("\n".join(o) + "\n", encoding="utf8")
    print(tot, dict(by))


if __name__ == "__main__":
    main()
